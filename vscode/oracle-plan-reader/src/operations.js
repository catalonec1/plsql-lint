const KEYS = Object.keys(OPS).sort((a, b) => b.length - a.length);

/** Explanation for an operation such as "TABLE ACCESS BY INDEX ROWID BATCHED", or null. */
function explain(operation) {
  const op = String(operation || '').toUpperCase().replace(/\s+/g, ' ').trim();
  for (const k of KEYS) if (op === k || op.startsWith(k + ' ')) return { key: k, text: OPS[k] };
  return null;
}

